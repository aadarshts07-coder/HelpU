/**
 * Fast lookup map by key
 */
export const CERTIFICATION_CATALOG_MAP = new Map<string, CertificationCatalogEntry>(
  CERTIFICATION_CATALOG.map((c) => [c.key, c])
);

/**
 * Find catalog entry by key or alias
 */
export function findCertificationByKeyOrAlias(query: string): CertificationCatalogEntry | undefined {
  if (!query) return undefined;
  const normalized = query.toLowerCase().trim();

  // Direct key match
  const byKey = CERTIFICATION_CATALOG_MAP.get(normalized);
  if (byKey) return byKey;

  // Search by name or alias
  return CERTIFICATION_CATALOG.find(
    (c) =>
      c.key.toLowerCase() === normalized ||
      c.name.toLowerCase() === normalized ||
      c.aliases.some((a) => a.toLowerCase() === normalized)
  );
}
