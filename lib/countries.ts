const countryLookup = new Map<string, CountryOption>();
ALL_COUNTRIES.forEach((c) => countryLookup.set(c.code, c));
POPULAR_COUNTRIES.forEach((c) => countryLookup.set(c.code, c));

export function getCountryByCode(code: string): CountryOption | undefined {
  if (!code) return undefined;
  return countryLookup.get(code.toLowerCase().trim());
}

export function getCountryName(code: string): string {
  if (!code) return '';
  const lower = code.toLowerCase().trim();
  if (lower === 'eu') return 'European Union';
  const match = countryLookup.get(lower);
  return match ? match.name : code.toUpperCase();
}

export function isEUCountry(code: string): boolean {
  return EU_COUNTRY_CODES.includes(code.toLowerCase().trim());
}

/**
 * Maps unstructured job location text (e.g. "San Jose, CA", "Bengaluru, India", "Stuttgart, Germany", "Remote - US")
 * to matching ISO alpha-2 country codes.
 */
export function extractCountryCodeFromLocation(locationText: string): string | null {
  if (!locationText) return null;
  const text = locationText.toLowerCase().trim();

  if (text.includes('remote') && (text === 'remote' || text.includes('worldwide') || text.includes('global'))) {
    return REMOTE_WORLDWIDE_CODE;
  }

  // Common high-frequency country/region matchers
  if (
    text.includes('united states') ||
    text.includes('usa') ||
    text.includes(' u.s.') ||
    text.endsWith(', us') ||
    text.endsWith(' us') ||
    text.includes('san francisco') ||
    text.includes('san jose') ||
    text.includes('new york') ||
    text.includes('seattle') ||
    text.includes('austin') ||
    text.includes('chicago') ||
    text.includes('boston') ||
    text.includes('california') ||
    text.includes('texas')
  ) {
    return 'us';
  }

  if (
    text.includes('india') ||
    text.includes('bengaluru') ||
    text.includes('bangalore') ||
    text.includes('hyderabad') ||
    text.includes('pune') ||
    text.includes('delhi') ||
    text.includes('mumbai') ||
    text.includes('chennai') ||
    text.includes('noida') ||
    text.includes('gurugram') ||
    text.includes('coimbatore')
  ) {
    return 'in';
  }

  if (
    text.includes('germany') ||
    text.includes('deutschland') ||
    text.includes('berlin') ||
    text.includes('munich') ||
    text.includes('stuttgart') ||
    text.includes('frankfurt')
  ) {
    return 'de';
  }

  if (
    text.includes('united kingdom') ||
    text.includes('uk') ||
    text.includes('london') ||
    text.includes('manchester') ||
    text.includes('cambridge') ||
    text.includes('edinburgh')
  ) {
    return 'gb';
  }

  if (
    text.includes('canada') ||
    text.includes('toronto') ||
    text.includes('vancouver') ||
    text.includes('montreal') ||
    text.includes('ottawa')
  ) {
    return 'ca';
  }

  if (text.includes('australia') || text.includes('sydney') || text.includes('melbourne')) {
    return 'au';
  }

  if (
    text.includes('singapore') ||
    text.includes('kallang') ||
    text.includes('central region') ||
    text.includes('jurong') ||
    text.includes('woodlands') ||
    text.includes('tampines') ||
    text.includes('bedok') ||
    text.includes('changi') ||
    text.includes('novena') ||
    text.includes('marina bay') ||
    text.includes('orchard') ||
    text.includes('queenstown') ||
    text.includes('bukit timah') ||
    text.includes('pasir ris') ||
    text.includes('yishun') ||
    text.includes('serangoon') ||
    text.includes('hougang') ||
    text.includes('ang mo kio') ||
    text.includes('clementi') ||
    text.includes('sembawang') ||
    text.includes('bishan') ||
    text.includes('tanjong pagar') ||
    text.includes('raffles place')
  ) {
    return 'sg';
  }

  if (text.includes('united arab emirates') || text.includes('uae') || text.includes('dubai')) {
    return 'ae';
  }

  if (text.includes('netherlands') || text.includes('amsterdam')) {
    return 'nl';
  }

  if (text.includes('ireland') || text.includes('dublin')) {
    return 'ie';
  }

  if (text.includes('france') || text.includes('paris')) {
    return 'fr';
  }

  if (text.includes('spain') || text.includes('madrid') || text.includes('barcelona')) {
    return 'es';
  }

  if (text.includes('switzerland') || text.includes('zurich') || text.includes('geneva')) {
    return 'ch';
  }

  if (text.includes('japan') || text.includes('tokyo')) {
    return 'jp';
  }

  // General pass against all country names
  for (const c of ALL_COUNTRIES) {
    if (text.includes(c.name.toLowerCase())) {
      return c.code;
    }
  }

  return null;
}
