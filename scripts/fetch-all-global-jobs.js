function generateFingerprint(title, company, canonicalId) {
  const normTitle = (title || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const normCompany = (company || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const normLoc = (canonicalId || '').toLowerCase().replace(/[^a-z0-9-]/g, '');
  return crypto.createHash('sha256').update(`${normTitle}_${normCompany}_${normLoc}`).digest('hex').substring(0, 24);
}

